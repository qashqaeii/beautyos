def _status_for_index(idx: int) -> tuple[str, bool]:
    bucket = (idx * 13) % 100
    if bucket < 7:
        return "vip", True
    if bucket < 18:
        return "new", False
    if bucket < 30:
        return "inactive", False
    return "active", bucket % 12 == 0


def _build_customers(target: int = 150) -> tuple[tuple[str, str, bool, int], ...]:
    rows = list(_CUSTOMERS_CORE)
    rng = random.Random(88421)
    used_names = {r[0] for r in rows}
    idx = len(rows) + 1
    while len(rows) < target:
        name = f"{rng.choice(_FIRST_NAMES)} {rng.choice(_LAST_NAMES)}"
        if name in used_names:
            continue
        used_names.add(name)
        status, is_vip = _status_for_index(idx)
        rows.append((name, status, is_vip, idx % 97 + 1))
        idx += 1
    return tuple(rows)


